from graphviz import Digraph

# Flowchart of Parking Lot Management System (Stack)
dot = Digraph('flowchart', format='png', graph_attr={'dpi': '150', 'rankdir': 'LR'})
dot.attr('node', shape='box', style='rounded,filled', fillcolor='lightyellow', fontname='Arial')

dot.node('start', 'Start', shape='oval', fillcolor='lightgreen')
dot.node('load', 'Load lane (stack) from\nparking_data.dat')
dot.node('menu', 'Display Menu\nEnter choice', shape='parallelogram', fillcolor='lightblue')
dot.node('push', 'Park Car\nIs stack full?', shape='diamond', fillcolor='white')
dot.node('over', 'Show OVERFLOW')
dot.node('dopush', 'PUSH car\nSave to file')
dot.node('pop', 'Remove Last Car\nIs stack empty?', shape='diamond', fillcolor='white')
dot.node('under', 'Show UNDERFLOW')
dot.node('dopop', 'POP car\nShow fee, Save')
dot.node('any', 'Remove Any Car:\nPOP cars into temp stack,\nPOP required car,\nPUSH temp cars back')
dot.node('peek', 'PEEK: show car\nnear gate')
dot.node('disp', 'Display lane\nfrom TOP to bottom')
dot.node('search', 'Search car,\nshow cars in front')
dot.node('stop', 'Exit', shape='oval', fillcolor='lightcoral')

dot.edge('start', 'load')
dot.edge('load', 'menu')
dot.edge('menu', 'push', label='1')
dot.edge('push', 'over', label='Yes')
dot.edge('push', 'dopush', label='No')
dot.edge('menu', 'pop', label='2')
dot.edge('pop', 'under', label='Yes')
dot.edge('pop', 'dopop', label='No')
dot.edge('menu', 'any', label='3')
dot.edge('menu', 'peek', label='4')
dot.edge('menu', 'disp', label='5')
dot.edge('menu', 'search', label='6')
dot.edge('menu', 'stop', label='7')
for n in ['over', 'dopush', 'under', 'dopop', 'any', 'peek', 'disp', 'search']:
    dot.edge(n, 'menu', style='dashed', color='gray')

dot.render('flowchart', cleanup=True)
print("Flowchart generated as 'flowchart.png'")
