from graphviz import Digraph

# Flowchart of Hospital Management System (Python + MySQL)
dot = Digraph('flowchart', format='png', graph_attr={'dpi': '150', 'rankdir': 'LR'})
dot.attr('node', shape='box', style='rounded,filled', fillcolor='lightyellow', fontname='Arial')

dot.node('start', 'Start', shape='oval', fillcolor='lightgreen')
dot.node('conn', 'Connect to MySQL\nCreate database & tables')
dot.node('ok', 'Connected?', shape='diamond', fillcolor='white')
dot.node('err', 'Show error')
dot.node('menu', 'Display Menu\nEnter choice', shape='parallelogram', fillcolor='lightblue')
dot.node('doc', 'Add / Show Doctors\n(INSERT, SELECT ... WHERE)')
dot.node('pat', 'Register / Search Patient\n(INSERT, SELECT ... LIKE)')
dot.node('book', 'Book Appointment\n(INSERT)')
dot.node('cancel', 'Cancel Appointment\n(UPDATE)')
dot.node('show', 'Show Appointments\n(JOIN of 3 tables)')
dot.node('rep', 'Reports\n(GROUP BY, COUNT, SUM,\nMIN, MAX, AVG)')
dot.node('commit', 'commit() changes')
dot.node('close', 'Close connection', shape='box')
dot.node('stop', 'Exit', shape='oval', fillcolor='lightcoral')

dot.edge('start', 'conn')
dot.edge('conn', 'ok')
dot.edge('ok', 'err', label='No')
dot.edge('err', 'stop')
dot.edge('ok', 'menu', label='Yes')
dot.edge('menu', 'doc', label='1, 2')
dot.edge('menu', 'pat', label='3, 4')
dot.edge('menu', 'book', label='5')
dot.edge('menu', 'cancel', label='6')
dot.edge('menu', 'show', label='7')
dot.edge('menu', 'rep', label='8')
dot.edge('menu', 'close', label='9')
dot.edge('close', 'stop')
for n in ['doc', 'pat', 'book', 'cancel']:
    dot.edge(n, 'commit')
dot.edge('commit', 'menu', style='dashed', color='gray')
dot.edge('show', 'menu', style='dashed', color='gray')
dot.edge('rep', 'menu', style='dashed', color='gray')

dot.render('flowchart', cleanup=True)
print("Flowchart generated as 'flowchart.png'")
